#!/usr/bin/env python3
"""Generate typed models from packages/contracts/schemas/*.schema.json.

Outputs (never edit by hand):
  services/policy/contracts/contracts_gen.go
  services/receipts/app/contracts_gen.py
  apps/dashboard/src/contracts.gen.ts

Guardrail: a JSON-Schema `number` (float) is rejected on any property whose name
looks like money. Money is always `Money` (integer minor units + currency).
"""
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCHEMAS = Path(__file__).parent / "schemas"
MONEYISH = re.compile(r"amount|total|price|money|cost|rate", re.I)
HEADER = "Code generated by packages/contracts/generate.py; DO NOT EDIT."


def load():
    out = {}
    for p in sorted(SCHEMAS.glob("*.schema.json")):
        d = json.loads(p.read_text())
        out[d["title"]] = d
    return out


def ref_name(prop):
    return prop["$ref"].split(".")[0]


def order(schemas):
    seen, res = set(), []

    def visit(n):
        if n in seen:
            return
        seen.add(n)
        d = schemas[n]
        for pr in d.get("properties", {}).values():
            for r in ([pr] + ([pr["items"]] if "items" in pr else [])):
                if "$ref" in r:
                    visit(ref_name(r))
        res.append(n)

    for n in sorted(schemas):
        visit(n)
    return res


def check(schemas):
    for n, d in schemas.items():
        for k, pr in d.get("properties", {}).items():
            if pr.get("type") == "number" and MONEYISH.search(k):
                sys.exit(f"{n}.{k}: float type on a money-like field is forbidden")


def camel(s):
    return "".join({"id": "ID", "url": "URL"}.get(p, p.capitalize()) for p in s.split("_"))


def is_enum(d):
    return d.get("type") == "string" and "enum" in d


# ---------- Go ----------
def go(schemas):
    L = [f"// {HEADER}", "", "package contracts", ""]
    for n in order(schemas):
        d = schemas[n]
        if is_enum(d):
            L.append(f"// {n}: {d['description']}")
            L.append(f"type {n} string\n\nconst (")
            for v in d["enum"]:
                L.append(f'\t{n}{camel(v)} {n} = "{v}"')
            L += [")", ""]
            continue
        L.append(f"// {n}: {d['description']}")
        L.append(f"type {n} struct {{")
        for k, pr in d["properties"].items():
            req = k in d["required"]
            t = go_type(pr)
            if not req:
                t = "*" + t
            tag = k if req else k + ",omitempty"
            L.append(f'\t{camel(k)} {t} `json:"{tag}"`')
        L += ["}", ""]
    return "\n".join(L)


def go_type(pr):
    if "$ref" in pr:
        return ref_name(pr)
    t = pr["type"]
    if t == "string":
        return "string"
    if t == "integer":
        return "int64"
    if t == "number":
        return "float64"
    if t == "boolean":
        return "bool"
    if t == "array":
        return "[]" + go_type(pr["items"])
    sys.exit(f"unsupported type {t}")


# ---------- Python ----------
def py(schemas):
    L = [f"# {HEADER}", "# ruff: noqa", "from __future__ import annotations", "", "from typing import Literal, Optional", "", "from pydantic import BaseModel", ""]
    for n in order(schemas):
        d = schemas[n]
        if is_enum(d):
            vals = ", ".join(json.dumps(v) for v in d["enum"])
            L += [f"{n} = Literal[{vals}]", ""]
            continue
        L += ["", f"class {n}(BaseModel):", f'    """{d["description"]}"""', ""]
        for k, pr in d["properties"].items():
            t = py_type(pr)
            if k not in d["required"]:
                L.append(f"    {k}: Optional[{t}] = None")
            else:
                L.append(f"    {k}: {t}")
        L.append("")
    return "\n".join(L) + "\n"


def py_type(pr):
    if "$ref" in pr:
        return ref_name(pr)
    return {"string": "str", "integer": "int", "number": "float", "boolean": "bool"}.get(pr["type"]) or (
        f"list[{py_type(pr['items'])}]" if pr["type"] == "array" else sys.exit("bad type")
    )


# ---------- TypeScript ----------
def ts(schemas):
    L = [f"// {HEADER}", ""]
    for n in order(schemas):
        d = schemas[n]
        if is_enum(d):
            L.append(f"export type {n} = " + " | ".join(json.dumps(v) for v in d["enum"]) + ";")
            L.append("")
            continue
        L.append(f"/** {d['description']} */")
        L.append(f"export interface {n} {{")
        for k, pr in d["properties"].items():
            opt = "" if k in d["required"] else "?"
            L.append(f"  {k}{opt}: {ts_type(pr)};")
        L += ["}", ""]
    return "\n".join(L)


def ts_type(pr):
    if "$ref" in pr:
        return ref_name(pr)
    t = pr["type"]
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean"}.get(t) or f"{ts_type(pr['items'])}[]"


def main():
    s = load()
    check(s)
    outs = {
        ROOT / "services/policy/contracts/contracts_gen.go": go(s),
        ROOT / "services/receipts/app/contracts_gen.py": py(s),
        ROOT / "apps/dashboard/src/contracts.gen.ts": ts(s),
    }
    for p, txt in outs.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(txt)
        if p.suffix == ".go" and shutil.which("gofmt"):
            subprocess.run(["gofmt", "-w", str(p)], check=True)
        print("wrote", p.relative_to(ROOT))


if __name__ == "__main__":
    main()
